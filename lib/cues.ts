export function cueDone(c: Cue, inputs: Record<string, unknown>): boolean {
  const has = (k: string) => {
    const v = inputs[k];
    return v !== undefined && v !== null && v !== "" && !(Array.isArray(v) && v.length === 0);
  };
  return c.all ? c.keys.every(has) : c.keys.some(has);
}
